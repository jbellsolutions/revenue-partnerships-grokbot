#!/usr/bin/env python3
"""Run one worker job with its switches. cron calls this; so does orders.py.

    run_job.py <job> [--order <id>] [key=value ...]     key=value fills {placeholders} in the job's cmd
    run_job.py --crontab                                  print the crontab for every scheduled job
    run_job.py --list                                     jobs, tiers and switches

A job runs only if context/worker-jobs-on.md says `<job>: on` (or `test`, which sets WORKER_TEST=1 so jobs keep to
drafts and state/test/). A guarded job refuses while STOP is set. A job with an "approval" runs only while that
message type is auto in context/standing-approvals.md. Every run is logged to state/jobs/<job>.jsonl."""
import json, os, re, subprocess, sys, time, pathlib

PACK = pathlib.Path(__file__).resolve().parents[1]
HOME = pathlib.Path(os.environ.get("WORKER_HOME", "/opt/revenue-worker"))
JOBS = json.loads((PACK / "worker" / "jobs.json").read_text())["jobs"]
os.environ.update({"WORKER_LOCAL": "1", "BOT_HOME": str(HOME)}); os.environ.setdefault("GTM_HOME", str(HOME / "gtm-box"))


def switch(job):
    f = HOME / "context" / "worker-jobs-on.md"
    for l in (f.read_text(errors="ignore").splitlines() if f.exists() else []):
        m = re.match(rf"\s*{re.escape(job)}\s*:\s*(\w+)", l)
        if m:
            return m.group(1).lower()
    return "off"


def log(job, rec):
    d = HOME / "state" / "jobs"; d.mkdir(parents=True, exist_ok=True)
    with (d / f"{job}.jsonl").open("a") as h:
        h.write(json.dumps({"t": int(time.time()), **rec}) + "\n")


def main(a):
    if not a or a[0] in ("-h", "--help"):
        print(__doc__); return 2
    if a[0] == "--list":
        for k, v in JOBS.items():
            print(f"{k:16} {v['tier']:12} {v.get('cron') or 'on order':20} {switch(k)}")
        return 0
    if a[0] == "--crontab":
        py = sys.executable
        print(f"# revenue-worker jobs (UTC). Generated by run_job.py --crontab. WORKER_HOME={HOME}")
        print("SHELL=/bin/bash")  # the server clock is UTC (install.sh checks)
        # cron's own PATH is /usr/bin:/bin, which hides an npm- or pipx-installed codex or hermes; think.py would then skip both
        print("PATH=/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin")
        for k, v in JOBS.items():
            if v.get("cron"):
                print(f"{v['cron']} set -a; . /etc/revenue-worker.env; set +a; {py} {PACK}/worker/run_job.py {k} >> {HOME}/log/{k}.log 2>&1")
        return 0
    job = a[0]
    if job not in JOBS:
        print(f"unknown job {job}"); return 2
    spec, sw = JOBS[job], switch(job)
    params = dict(x.split("=", 1) for x in a[1:] if "=" in x and not x.startswith("--"))
    # Parameters come from the bot's orders: plain names only. Never a flag, a path out, or a stand-in for {pack}/{home}.
    if any(k in ("pack", "home") or not re.fullmatch(r"[a-z_]{1,20}", k) or not re.fullmatch(r"[\w.@:+-]{1,80}", str(v))
           or str(v).startswith("-") or ".." in str(v) for k, v in params.items()):
        log(job, {"code": 2, "tail": "refused: parameters must be plain names"}); print("refused: parameters must be plain names"); return 2
    if sw not in ("on", "test"):
        log(job, {"code": None, "tail": "SKIPPED_OFF"}); print("SKIPPED_OFF"); return 0
    if spec.get("guarded") and (HOME / "context" / "STOP").exists():
        log(job, {"code": None, "tail": "STOPPED"}); print("STOPPED"); return 0
    if spec.get("approval"):
        r = subprocess.run([sys.executable, str(PACK / "guards" / "scripts" / "send_guard.py"), spec["approval"]], capture_output=True, text=True)
        if r.returncode != 0 or sw == "test":
            log(job, {"code": None, "tail": f"HELD: {spec['approval']} not auto"}); print(f"HELD: {spec['approval']} not auto"); return 0
    try:
        cmd = [c.format(pack=PACK, home=HOME, **params) for c in spec["cmd"]]
    except KeyError as e:
        print(f"missing parameter {e}"); return 2
    env = {**os.environ, "WORKER_TEST": "1" if sw == "test" else "0"}
    t0 = time.time()
    try:
        r = subprocess.run([sys.executable if cmd[0] == "python3" else cmd[0], *cmd[1:]], capture_output=True, text=True, env=env,
                           timeout=int(spec.get("timeout", 3600)), cwd=str(PACK / "worker" / "jobs"))
        code, tail = r.returncode, (r.stdout.strip().splitlines() or r.stderr.strip().splitlines() or [""])[-1]
    except subprocess.TimeoutExpired:
        code, tail = 124, "timeout"
    log(job, {"code": code, "tail": tail[:300], "secs": round(time.time() - t0, 1), "order": a[a.index("--order") + 1] if "--order" in a else None})
    subprocess.run([sys.executable, str(PACK / "guards" / "scripts" / "beat.py"), "write", f"worker-{job}", tail[:200]], capture_output=True)
    print(tail)
    return 0 if code == 0 else 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
